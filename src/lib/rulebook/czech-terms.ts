export function czechSrdItemMeta(meta: string): string {
  const match = /^([A-Za-z ]+?)(\s*\([^)]*\))?,\s*(common|uncommon|rare|very rare|legendary|artifact)(.*)$/i.exec(meta);
  if (!match) return meta;
  const type = CZECH_ITEM_TYPES[Object.keys(CZECH_ITEM_TYPES).find((k) => k.toLowerCase() === match[1].toLowerCase()) ?? ""];
  const rarity = CZECH_RARITY[match[3].toLowerCase()];
  if (!type || !rarity) return meta;
  const suffix = match[4].replace(/requires attunement/gi, "vyžaduje sladění");
  return `${type.label}${match[2] ?? ""}, ${rarity[type.gender]}${suffix}`;
}

export function czechSrdSpellMeta(meta: string): string {
  // The English import writes "3rd-level evocation", optionally "(ritual)".
  // Some print variants begin with the school and end in "cantrip".
  const level = /^(\d+)(?:st|nd|rd|th)-level\s+(\w+)(.*)$/i.exec(meta);
  if (level) {
    const school = CZECH_SCHOOLS[level[2].toLowerCase()];
    if (school) return `${school} ${level[1]}. úrovně${level[3].replace(/\britual\b/gi, "rituál")}`;
  }
  const cantrip = /^(\w+)\s+cantrip(.*)$/i.exec(meta);
  if (cantrip) {
    const school = CZECH_SCHOOLS[cantrip[1].toLowerCase()];
    if (school) return `${school} (trik)${cantrip[2]}`;
  }
  return meta;
}

export function czechSrdSpellGroup(group: string): string {
  if (group === "Cantrips") return "Triky";
  const level = /^(\d+)(?:st|nd|rd|th) Level$/.exec(group);
  return level ? `${level[1]}. úroveň` : group;
}

const TITLES: Readonly<Record<string, Readonly<Record<string, string>>>> = {
  class: CZECH_CLASSES,
  race: CZECH_RACES,
  monster: CZECH_MONSTERS,
  spell: CZECH_SPELLS,
  item: CZECH_ITEMS,
};

// Titles are display-only. Kind prevents a name shared by a class and a
// monster, e.g. Druid, from being interpreted as a different rules entity.
export function czechSrdTitle(title: string, kind: string): string {
  return TITLES[kind]?.[title] ?? title;
}

// Keep English search / italics references pointing at the same canonical ID.
export function czechSrdEnglishAliases(kind: string): Readonly<Record<string, string>> {
  return TITLES[kind] ?? {};
}
